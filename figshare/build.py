#!/usr/bin/env python3
"""Build the five Figshare items for the golden-window conjecture, and the text to paste into Figshare.

  python3 figshare/build.py              # rebuilds everything under figshare/
  python3 figshare/build.py --out DIR    # builds into DIR (used by verification/check_figshare.py)

Needs: matplotlib, pillow and fonttools at the versions in requirements.txt, pdflatex (TeX Live with tikzposter
and beamer), pdftoppm (poppler), and git with the commit SOFTWARE_COMMIT available. Every output is deterministic, so a rebuild
gives the same bytes. The outputs are not edited by hand; this script or its modules are changed and the outputs rebuilt.

Items (each in its own directory):
  figure/    the figure (PNG, SVG, and the PDF used by the poster and the slides)
  dataset/   the tables of the paper as CSV, with a data dictionary (README.md)
  software/  the verification scripts at SOFTWARE_COMMIT as a zip made by git archive, with a list of contents
  poster/    an A0 portrait poster (LaTeX source and PDF)
  slides/    a short presentation (LaTeX source and PDF)
and METADATA.md (the fields to paste) and SHA256SUMS (the hashes of all of the above).
"""
import hashlib
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import documents  # noqa: E402
import figure  # noqa: E402
import tables  # noqa: E402

SOFTWARE_COMMIT = "c2a47fd9fd1a4cbd9940e0ec78895b47689f9313"
SOFTWARE_PATHS = ["LICENSE-CODE", "requirements.txt", "verification/run_scripts.py", "scripts", "expected"]
SHORT = SOFTWARE_COMMIT[:7]
ZIP_NAME = f"golden-window-resolution-scripts-{SHORT}.zip"
GROUPS = ["curve", "edges", "symbolic", "symbolic-referee", "trinity"]


def git(*args):
    return subprocess.run(["git", "-C", ROOT, *args], check=True, capture_output=True).stdout


def software(outdir):
    os.makedirs(outdir, exist_ok=True)
    data = git("archive", "--format=zip", f"--prefix=golden-window-resolution-{SHORT}/", SOFTWARE_COMMIT, "--", *SOFTWARE_PATHS)
    with open(os.path.join(outdir, ZIP_NAME), "wb") as fh:
        fh.write(data)
    entries = []
    for line in git("ls-tree", "-r", "-l", SOFTWARE_COMMIT, "--", *SOFTWARE_PATHS).decode().splitlines():
        meta, path = line.split("\t", 1)
        entries.append((path, int(meta.split()[3])))
    scripts = [p for p, _ in entries if p.startswith("scripts/") and p.endswith(".py")]
    outputs = [p for p, _ in entries if p.startswith("expected/")]
    lines = [
        "# Software: verification scripts for the resolution of the golden-window conjecture", "",
        "Generated by `figshare/build.py`. It is not edited by hand.", "",
        f"`{ZIP_NAME}` is `git archive` of commit `{SOFTWARE_COMMIT}` of",
        "https://github.com/cpsbvbng26-dotcom/golden-window-resolution, restricted to the paths below.",
        "Licence: MIT (`LICENSE-CODE` in the archive). The outputs in `expected/` are what the scripts print.", "",
        f"The archive holds {len(entries)} files: {len(scripts)} Python scripts and modules under `scripts/`, "
        f"{len(outputs)} expected outputs under `expected/`, the runner `verification/run_scripts.py`, "
        "`requirements.txt` and `LICENSE-CODE`.", "",
        "## How to run", "",
        "```",
        f"unzip {ZIP_NAME}",
        f"cd golden-window-resolution-{SHORT}",
        "python3 -m pip install -r requirements.txt",
        "python3 verification/run_scripts.py " + " ".join(GROUPS),
        "```", "",
        "The runner runs each script that has an expected output, and compares what it prints with",
        "`expected/<group>/<name>.out` byte for byte. Each script uses exact rationals, fixed precision and fixed",
        "random seeds. The group `continuity` of the runner belongs to a second paper and is not in this archive,",
        "so the groups are named on the command line.", "",
        "## Contents", "",
        "| path | bytes |", "| --- | --- |",
    ]
    lines += [f"| `{p}` | {n} |" for p, n in entries]
    with open(os.path.join(outdir, "README.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return {"files": len(entries), "scripts": len(scripts), "outputs": len(outputs)}


def pdf_pages(path):
    import pypdf
    return len(pypdf.PdfReader(path).pages)


