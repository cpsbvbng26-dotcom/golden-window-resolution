def sha256sums(outroot):
    rows = []
    for dp, dns, fns in os.walk(outroot):
        dns.sort()
        for fn in sorted(fns):
            rel = os.path.relpath(os.path.join(dp, fn), outroot)
            if rel == "SHA256SUMS" or fn.endswith(".py") or "__pycache__" in rel:
                continue
            with open(os.path.join(dp, fn), "rb") as fh:
                rows.append(f"{hashlib.sha256(fh.read()).hexdigest()}  {rel}")
    with open(os.path.join(outroot, "SHA256SUMS"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(sorted(rows, key=lambda r: r.split("  ", 1)[1])) + "\n")


def build(outroot):
    os.makedirs(outroot, exist_ok=True)
    built = tables.build(os.path.join(outroot, "dataset"))
    finfo = figure.build(os.path.join(outroot, "figure"))
    sinfo = software(os.path.join(outroot, "software"))
    pdfs = documents.build(outroot, built, os.path.join(outroot, "figure", "golden-window-figure.pdf"))
    pages = {k: pdf_pages(v) for k, v in pdfs.items()}
    info = {"figure": finfo, "dataset": built, "software": sinfo, "pages": pages}
    with open(os.path.join(outroot, "METADATA.md"), "w", encoding="utf-8") as fh:
        fh.write(metadata(info))
    sha256sums(outroot)
    return info


